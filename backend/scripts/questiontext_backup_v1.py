def difficulty(marks: int) -> str:
    """Map a question's total marks to a difficulty band.

    Thresholds were tuned to the whole-question mark totals of IGCSE 0580
    Paper 4 (multi-part questions, ~5-21 marks each), giving a roughly balanced
    easy/medium/hard split. NOTE: if questions from papers with much smaller
    per-question marks are added (e.g. Paper 2), revisit these cutoffs — they
    would otherwise skew everything toward "easy".
    """
    return "easy" if marks <= 10 else "medium" if marks <= 13 else "hard"


def _log_summary(questions: list[dict]) -> None:
    """Print a breakdown of the seeded set: total, images, topic, difficulty."""
    total = len(questions)
    with_image = sum(1 for q in questions if q.get("hasImage"))
    by_topic = Counter(q.get("topic", "?") for q in questions)
    by_difficulty = Counter(q.get("difficulty", "?") for q in questions)

    print("Summary:")
    print(f"  Total questions: {total}")
    print(f"  hasImage true:   {with_image} of {total}")
    print("  By topic:")
    for topic, count in by_topic.most_common():
        print(f"    {topic}: {count}")
    print("  By difficulty:")
    for level in ("easy", "medium", "hard"):
        print(f"    {level}: {by_difficulty.get(level, 0)}")


def seed_questions() -> None:
    """Batch-write every question in QUESTIONS to Firestore and log the result."""
    if not QUESTIONS:
        print("No questions to seed — the QUESTIONS list is empty. Nothing written.")
        return

    # Recompute difficulty from marks so the stored value always reflects the
    # current thresholds, regardless of what is hard-coded in the data above.
    for q in QUESTIONS:
        q["difficulty"] = difficulty(q["marks"])

    try:
        written = batch_write_custom_questions(QUESTIONS)
        print(f"Seeding complete. {written} question(s) written to `questions`.")
        _log_summary(QUESTIONS)
    except Exception as exc:  # noqa: BLE001 — surface any failure to the operator
        print(f"Seeding failed: {exc}")
        raise


if __name__ == "__main__":
    seed_questions()
